"""Generate additive magical/regen profiles from pinned L2J class and NPC inputs.

python3 packages/data/scripts/gen_class_phase3.py --datapack PATH --game PATH [--check]
Owns classes-phase3/*.toml, tables-phase3/*.toml and the appended keltir section.
"""
