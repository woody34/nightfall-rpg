#!/usr/bin/env python3
"""Generate tables-phase5/skill_promotions.toml (ruling P5-D19) from the pinned skill XML.

The B11 V7 skills (Spoil 254, Sweeper 42, Sowing 2097, Harvesting 2098) are deferred or absent in
the V6 skill bundle, and that bundle and its Phase3Rules hash must not change. This table names
them for V7 epochs only (the same pattern as D10):

- `[[promotions]]`: a skill that IS in the V6 bundle with runtime_status "deferred". The row names
  the level range 1..max_level and `clears`, which equals that skill's V6 blockers exactly;
- `[[additions]]`: a skill that is ABSENT from the V6 bundle. `additions.skill` is exactly the row
  gen_skills.py writes to skills-phase4/<id>.toml (gen_skills.generate_skill_toml, phase4=True,
  so the shapes cannot drift) and `clears` equals its generated blockers.

Every cleared blocker must be in the V7 engine's implemented-blocker constant (formula_revision 1,
Z lane); the generator refuses any other string. Phase5Rules hashes the table; V5/V6 never read it.

Herbs (P5-D17/P5-D19, Z lane api-inbox 2026-11-01): the 48 herb item skills (herbs.toml
`distinct_skill_ids`) are absent from the V6 bundle. A herb skill whose generated row has no
blocker is an addition with `clears = []` and `runtime_status = "executable"`. A herb skill with a
blocker outside the constant stays out of the table (its herb stays ITEM_CAPABILITY_DEFERRED); the
generator reports it with its exact blockers. `HERBS_BOUND` turns the herb rows on; the
Phase5Rules loader accepts a clean addition since Z lane 3.7 (e7afc82).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import tomllib
import xml.etree.ElementTree as ET

try:
    import gen_items
    import gen_skills
except ModuleNotFoundError:
    from packages.data.scripts import gen_items, gen_skills

ROOT = Path(__file__).resolve().parents[1]
OUT = 'tables-phase5/skill_promotions.toml'
# The V6 skill bundle: the semantic digest of skills-phase4/*.toml as gen_items.py records it
# (rules_manifest.toml `skill_bundle_sha256`), and the Phase3Rules hash that bundle binds at V6
# startup (`phase4_skill_rules_hash`). The table carries the latter for the Phase5Rules loader.
V6_SKILL_BUNDLE_SHA256 = '27d35a082f8951817fddf18e2d26dbc10bce37b726841999087c2ce6794ce000'
V6_SKILLS_PHASE3_HASH = '5c2378c9eab24f26fdef161c4965dc3567fc05eefe04186cdf095d84cad7f6d1'
V6_MANIFEST_DATA_SHA256 = 'f0e8dc63a0aa8d013b5c4ecf2c0698d64438f914a2a9bc099b48651af9923b5e'
FORMULA_REVISION = 1
# B11 (architecture decisions §7) and any skill the zone lane names later.
SKILLS = {254: 'Spoil', 42: 'Sweeper', 2097: 'Sowing', 2098: 'Harvesting'}
# The loader accepts a clean addition since Z lane e7afc82 (merged at f65049b).
HERBS_BOUND = True
# The V7 engine's implemented-blocker constant for FORMULA_REVISION (Z lane, api-inbox 2026-11-01).
V7_IMPLEMENTED_BLOCKERS = frozenset({
    'effect:Spoil', 'effect:Sweeper', 'effect:ConsumeBody', 'cond:player:canSweep', 'target:NPC_BODY',
    'effect:Sow', 'effect:Harvesting',
})
HEADER = ['# GENERATED by packages/data/scripts/gen_skill_promotions.py from the pinned L2J High Five source',
          '# (packages/data/SOURCES.md). Do not edit by hand; regenerate instead.',
          '# P5-D19: V7 skill promotions and additions; the V6 skill bundle is unchanged.', '']


class SourceError(ValueError):
    """Missing, inconsistent or unsupported input."""


def v6_skills(root: Path = ROOT) -> dict[int, dict]:
    """The committed V6 skill rows, refused unless they are the bundle this table was made for."""
    manifest = tomllib.loads((root / 'tables-phase4/rules_manifest.toml').read_text())
    if manifest['data_sha256'] != V6_MANIFEST_DATA_SHA256 or manifest['skill_bundle_sha256'] != V6_SKILL_BUNDLE_SHA256:
        raise SourceError('the V6 skill bundle changed; the promotions must not be regenerated against another V6 hash')
    paths = sorted((root / 'skills-phase4').glob('*.toml'), key=lambda p: int(p.stem))
    rows = [tomllib.loads(path.read_text()) for path in paths]
    if gen_items.digest(rows) != V6_SKILL_BUNDLE_SHA256:
        raise SourceError('skills-phase4/ does not match the V6 skill bundle digest')
    return {row['id']: row for row in rows}


def skill_line(dp: Path, rel: str, sid: int) -> int:
    for number, line in enumerate((dp / rel).read_text().splitlines(), start=1):
        if f'<skill id="{sid}"' in line:
            return number
    raise SourceError(f'skill {sid} not found in {rel}')


def nest(text: str, prefix: str) -> list[str]:
    """A generate_skill_toml document as the body of `[prefix]` (sub-tables re-rooted under it)."""
    out = [f'[{prefix}]']
    for line in text.splitlines():
        if line.startswith('#') or (not line and out[-1] == f'[{prefix}]'):
            continue
        if line.startswith('[['):
            out.append(f'[[{prefix}.{line[2:]}')
        elif line.startswith('['):
            out.append(f'[{prefix}.{line[1:]}')
        else:
            out.append(line)
    return out


def herb_skill_ids(root: Path = ROOT) -> list[int]:
    """The 48 herb item skills (herbs.toml, generated by gen_economy from the pinned items)."""
    ids = tomllib.loads((root / 'tables-phase5/herbs.toml').read_text())['distinct_skill_ids']
    if len(ids) != 48 or ids != sorted(set(ids)):
        raise SourceError('herbs.toml distinct_skill_ids is not the 48 ascending herb skills')
    return ids


def herb_rows(datapack, all_skills, v6: dict, dp: Path, root: Path = ROOT):
    """(clean additions, blocked {id: blockers}, sources) of the herb skills."""
    herbs = herb_skill_ids(root)
    if set(herbs) & (set(v6) | set(SKILLS)):
        raise SourceError('a herb skill is in the V6 bundle or is a B11 skill')
    missing = sorted(set(herbs) - set(all_skills))
    if missing:
        raise SourceError(f'herb skills absent from the pinned datapack: {missing}')
    _, blockers = gen_skills.compute_all_blockers(all_skills, set(herbs), phase4=True)
    clean, blocked, sources = [], {}, []
    for sid in herbs:
        rel, node = all_skills[sid]
        generated = sorted(blockers[sid])
        if generated:
            blocked[sid] = generated
            continue
        sources.append({'repository': gen_skills.DATAPACK_REPOSITORY, 'revision': gen_skills.DATAPACK_REVISION,
                        'file': rel, 'line': skill_line(dp, rel, sid), 'skill_id': sid})
        text = gen_skills.generate_skill_toml(sid, rel, node, set(), phase4=True)
        skill = tomllib.loads(text)
        if skill['runtime_status'] != 'executable' or skill['blockers']:
            raise SourceError(f'herb skill {sid}: the generated row is not executable without blockers')
        clean.append({'clears': [], 'text': text, 'skill': skill})
    return clean, blocked, sources


def generate(dp: Path = gen_items.DEFAULT_DP, root: Path = ROOT, herbs: bool = HERBS_BOUND):
    v6 = v6_skills(root)
    datapack = gen_skills.Datapack(dp)
    all_skills = gen_skills.load_all_datapack_skills(datapack, phase4=True)
    missing = sorted(set(SKILLS) - set(all_skills))
    if missing:
        raise SourceError(f'skills absent from the pinned datapack: {missing}')
    ids, blockers = gen_skills.compute_all_blockers(all_skills, set(SKILLS), phase4=True)
    promotions, additions, sources = [], [], []
    for sid in sorted(SKILLS):
        rel, node = all_skills[sid]
        if node.get('name') != SKILLS[sid]:
            raise SourceError(f'skill {sid} is {node.get("name")!r}, not {SKILLS[sid]!r}')
        sources.append({'repository': gen_skills.DATAPACK_REPOSITORY, 'revision': gen_skills.DATAPACK_REVISION,
                        'file': rel, 'line': skill_line(dp, rel, sid), 'skill_id': sid})
        generated = sorted(blockers[sid])
        if not generated:
            raise SourceError(f'skill {sid} has no blocker: it needs no promotion')
        outside = sorted(set(generated) - V7_IMPLEMENTED_BLOCKERS)
        if outside:
            raise SourceError(f'skill {sid} blockers outside the V7 implemented set: {outside}')
        levels = int(node.get('levels', '1'))
        if sid in v6:
            row = v6[sid]
            if row['runtime_status'] != 'deferred' or sorted(row['blockers']) != generated or row['max_level'] != levels:
                raise SourceError(f'skill {sid}: the V6 row disagrees with the pinned XML')
            promotions.append({'id': sid, 'min_level': 1, 'max_level': row['max_level'], 'clears': sorted(row['blockers'])})
        else:
            text = gen_skills.generate_skill_toml(sid, rel, node, set(generated), phase4=True)
            skill = tomllib.loads(text)
            if skill['runtime_status'] != 'deferred' or skill['blockers'] != generated:
                raise SourceError(f'skill {sid}: the generated row is not deferred with its blockers')
            additions.append({'clears': generated, 'text': text, 'skill': skill})
    blocked = {}
    if herbs:
        clean, blocked, herb_sources = herb_rows(datapack, all_skills, v6, dp, root)
        additions += clean
        sources += herb_sources
        additions.sort(key=lambda a: a['skill']['id'])
        sources.sort(key=lambda src: src['skill_id'])
    lines = list(HEADER)
    lines.append('sources = [')
    for src in sources:
        lines.append('  ' + gen_skills.toml_value(src) + ',')
    lines += [']', 'schema_version = 1', f'v6_skills_sha256 = "{V6_SKILLS_PHASE3_HASH}"', f'formula_revision = {FORMULA_REVISION}', '']
    for row in promotions:
        lines += ['[[promotions]]', f'id = {row["id"]}', f'min_level = {row["min_level"]}', f'max_level = {row["max_level"]}',
                  'clears = ' + gen_skills.toml_value(row['clears']), '']
    for row in additions:
        lines += ['[[additions]]', 'clears = ' + gen_skills.toml_value(row['clears'])]
        lines += nest(row['text'], 'additions.skill')
        lines.append('')
    content = '\n'.join(lines).rstrip('\n') + '\n'
    parsed = tomllib.loads(content)
    if [a['skill'] for a in parsed['additions']] != [a['skill'] for a in additions]:
        raise SourceError('additions.skill does not round-trip to the gen_skills row')
    if any(isinstance(v, float) for v in _leaves(parsed)):
        raise SourceError('float literal in the table')
    counts = {'promotions': [r['id'] for r in promotions], 'additions': [a['skill']['id'] for a in additions],
              'cleared': sorted({b for r in promotions for b in r['clears']} | {b for a in additions for b in a['clears']}),
              'blocked_herbs': {str(k): v for k, v in blocked.items()}}
    return content, counts


def _leaves(value):
    if isinstance(value, dict):
        for v in value.values():
            yield from _leaves(v)
    elif isinstance(value, list):
        for v in value:
            yield from _leaves(v)
    else:
        yield value


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--datapack', type=Path, default=gen_items.DEFAULT_DP)
    parser.add_argument('--game', type=Path, default=gen_items.DEFAULT_GAME, help='unused; check_all passes it')
    parser.add_argument('--out', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        content, counts = generate(args.datapack)
    except (ValueError, OSError, KeyError, ET.ParseError, gen_skills.SourceError) as error:
        print('gen_skill_promotions: ' + str(error), file=sys.stderr)
        return 2
    path = args.out / OUT
    if args.check:
        if not path.exists() or path.read_text() != content:
            print('gen_skill_promotions: stale: ' + OUT, file=sys.stderr)
            return 1
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    print('gen_skill_promotions: ' + json.dumps(counts, sort_keys=True))
    print('gen_skill_promotions: ' + ('check passed' if args.check else 'generated'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
