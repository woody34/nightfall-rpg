"""Additive NPC penalty and hit-condition tables for gen_class_phase3."""
import json
import re
import xml.etree.ElementTree as ET
from fractions import Fraction as F

NPC_CONFIG = 'src/main/resources/config/npc.properties'
FORMULAS = 'src/main/java/com/l2jserver/gameserver/model/stats/Formulas.java'
HIT_JAVA = 'src/main/java/com/l2jserver/gameserver/data/xml/impl/HitConditionBonusData.java'
HIT_XML = 'src/main/resources/data/stats/hitConditionBonus.xml'


def generate(game, dp, source):
    formula = (game / FORMULAS).read_text().splitlines()
    for lo, hi in ((713, 731), (776, 800), (887, 898)):
        branch = '\n'.join(formula[lo - 1:hi])
        for literal in ('getMinNPCLevelForDmgPenalty()', '>= 2',
                        'getLevel() - attacker.getActingPlayer().getLevel() - 1;'):
            if literal not in branch:
                raise ValueError(f'changed damage branch {lo}: {literal}')
    chance = '\n'.join(formula[1285:1314])
    for literal in ('getMinNPCLevelForDmgPenalty()', '>= 3',
                    'getLevel() - attacker.getActingPlayer().getLevel() - 2;',
                    'Rnd.get(100) < rate'):
        if literal not in chance:
            raise ValueError(f'changed chance branch: {literal}')
    hit_java = (game / HIT_JAVA).read_text()
    for literal in ('double mod = 100;', '(attacker.getZ() - target.getZ()) > 50',
                    '(attacker.getZ() - target.getZ()) < -50',
                    'return Math.max(mod / 100, 0);'):
        if literal not in hit_java:
            raise ValueError(f'changed hit condition: {literal}')
    config = (game / NPC_CONFIG).read_text().splitlines()
    out = ['# GENERATED by gen_class_phase3.py; additive V5 input only.', 'schema = 1',
           'q = 1000000', f'source = {source(NPC_CONFIG, "50-74", "NPC penalty configuration", game=True)}',
           f'formula_source = {source(FORMULAS, "713-731,776-800,887-898,1286-1301", "NPC level penalty branches", game=True)}',
           '# gap = target level - acting player level (not skill magic level).',
           '# Source indexing skips index 0: damage index=gap-1, chance index=gap-2.',
           '# All lists saturate to their final entry; gates failing return unity.',
           '# Magic-success uses MinNPCLevelForDmgPenalty, NOT the magic config value.',
           '# Chance factor scales the failure subtrahend, NOT success chance.']
    lists = {}
    for key in ('MinNPCLevelForDmgPenalty', 'MinNPCLevelForMagicPenalty',
                'DmgPenaltyForLvLDifferences', 'CritDmgPenaltyForLvLDifferences',
                'SkillDmgPenaltyForLvLDifferences', 'SkillChancePenaltyForLvLDifferences'):
        matches = [(i, line.strip()) for i, line in enumerate(config, 1)
                   if re.match(rf'^{key}\s*=', line)]
        if len(matches) != 1:
            raise ValueError(f'missing/duplicate config {key}')
        line, literal = matches[0]
        values = literal.split('=')[1].strip().split(',')
        if any(not re.fullmatch(r'\d+(?:\.\d+)?', v) for v in values):
            raise ValueError(f'invalid config {key}')
        lists[key] = values
        out += ['', f'[config.{key}]', f'values = {json.dumps(values)}',
                f'values_q = {[int(F(v) * 1000000) for v in values]}',
                f'source = {source(NPC_CONFIG, str(line), key, game=True)}']
    # Explicit eligible mapping, including unreachable index-zero values above.
    for gap in range(2, 7):
        i = min(gap - 1, len(lists['DmgPenaltyForLvLDifferences']) - 1)
        ci = min(max(0, gap - 2), len(lists['SkillChancePenaltyForLvLDifferences']) - 1)
        normal = F(lists['DmgPenaltyForLvLDifferences'][i])
        crit = F(lists['CritDmgPenaltyForLvLDifferences'][i])
        skill = F(lists['SkillDmgPenaltyForLvLDifferences'][i])
        chance = F(lists['SkillChancePenaltyForLvLDifferences'][ci]) if gap >= 3 else F(1)
        out += ['', '[[rows]]', f'gap_min = {gap}', f'gap_max = {gap if gap < 6 else -1}',
                '# gap_max=-1 denotes no upper bound.', f'damage_index = {i}',
                f'chance_index = {ci if gap >= 3 else -1}']
        for key, value in (('physical', normal), ('physical_critical', crit),
                           ('magic', skill), ('physical_skill', skill * normal),
                           ('physical_skill_critical', skill * crit), ('magic_failure', chance)):
            out.append(f'{key}_q = {int(value * 1000000)}')
    penalty = '\n'.join(out) + '\n'
    text = (dp / HIT_XML).read_text()
    nodes = list(ET.fromstring(text))
    if {n.tag for n in nodes} != {'back', 'dark', 'front', 'high', 'low', 'rain', 'side'} or len(nodes) != 7:
        raise ValueError('unexpected hit-condition rows')
    out = ['# GENERATED by gen_class_phase3.py; additive V5 input only.', 'schema = 1',
           f'source = {source(HIT_XML, "3-9", "hitConditionBonus")}',
           f'formula_source = {source(HIT_JAVA, "92-118", "getConditionBonus", game=True)}',
           'base_percent = 100', 'height_threshold = 50', 'minimum_q = 0',
           '# high iff z difference >50; low iff <-50. Night applies dark.',
           '# Back/front/side exclusive in that order. Rain is loaded but unused.',
           '# Return max((100 + active bonuses)/100, 0). Height uses L2 source Z units.']
    for n in nodes:
        value = n.get('val')
        if not re.fullmatch(r'-?\d+', value or ''):
            raise ValueError('invalid hit-condition value')
        line = next(i for i, row in enumerate(text.splitlines(), 1) if f'<{n.tag} ' in row)
        out += ['', '[[rows]]', f'condition = {json.dumps(n.tag)}', f'percent = {value}',
                f'used = {str(n.tag != "rain").lower()}',
                f'source = {source(HIT_XML, str(line), n.tag)}']
    return {'tables-phase3/npc_level_penalty.toml': penalty,
            'tables-phase3/hit_condition_bonus.toml': '\n'.join(out) + '\n'}
