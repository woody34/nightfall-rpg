class SourceError(Exception):
    """The pinned source does not contain what this script expects."""


# ---------------------------------------------------------------------------
# Exact decimal helpers
# ---------------------------------------------------------------------------


def to_q(literal: str) -> int:
    """Exact Q-scaled integer of a decimal literal; fails if it is not exactly representable."""
    if not re.fullmatch(r"-?\d+(\.\d+)?", literal):
        raise SourceError(f"not a plain decimal: {literal!r}")
    scaled = Fraction(literal) * Q
    if scaled.denominator != 1:
        raise SourceError(f"{literal} is not exact at Q={Q}")
    return int(scaled)


def fraction_literal(value: Fraction) -> str:
    """Plain decimal string of a fraction whose denominator divides a power of ten."""
    for digits in range(0, 13):
        scaled = value * 10**digits
        if scaled.denominator == 1:
            return str(Decimal(int(scaled)).scaleb(-digits)) if digits else str(int(scaled))
    raise SourceError(f"{value} has no finite decimal form")


def round_half_up(value: Decimal, exponent: str) -> Decimal:
    return value.quantize(Decimal(exponent), rounding=ROUND_HALF_UP)


def closed_form(base: str, offset: Fraction, x: int, precision: int) -> Decimal:
    """base^(x + offset) evaluated in decimal at `precision` significant digits."""
    with localcontext() as ctx:
        ctx.prec = precision
        exponent = Decimal(offset.numerator) / Decimal(offset.denominator) + x
        return (exponent * Decimal(base).ln()).exp()


def closed_form_two_decimals(base: str, offset: Fraction, x: int) -> Decimal:
    """Round base^(x+offset) half-up to 0.01, doubling precision until two runs agree."""
    precision = 40
    previous = round_half_up(closed_form(base, offset, x, precision), "0.01")
    while True:
        precision *= 2
        current = round_half_up(closed_form(base, offset, x, precision), "0.01")
        if current == previous:
            return current
        if precision > 2000:
            raise SourceError(f"{base}^({x}{offset:+}) does not converge")
        previous = current


# ---------------------------------------------------------------------------
# Source access
# ---------------------------------------------------------------------------


class Repo:
    def __init__(self, root: Path, revision: str, label: str) -> None:
        head = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "HEAD"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
        if head != revision:
            raise SourceError(f"{label} clone is at {head}, expected pinned {revision}")
        self.root = root

    def text(self, rel: str) -> str:
        return (self.root / rel).read_text(encoding="utf-8")

    def line(self, rel: str, literal: str) -> str:
        """Return `literal` if a line of `rel` equals it after stripping whitespace."""
        if literal not in (ln.strip() for ln in self.text(rel).splitlines()):
            raise SourceError(f"{rel}: expected literal line not found: {literal}")
        return literal


def property_value(game: Repo, key: str) -> str:
    match = re.search(rf"^{key}\s*=\s*(\S+)\s*$", game.text(CONFIG), re.M)
    if not match:
        raise SourceError(f"{CONFIG}: {key} not set")
    return match.group(1)


def int_from(pattern: str, literal: str) -> int:
    match = re.search(pattern, literal)
    if not match:
        raise SourceError(f"pattern {pattern!r} not in {literal!r}")
    return int(match.group(1))


# ---------------------------------------------------------------------------
# TOML emission (hand-rolled so output is byte-stable)
# ---------------------------------------------------------------------------


def toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def toml_array(items: list[str], per_line: int = 10, indent: str = "    ") -> str:
    lines = [", ".join(items[i : i + per_line]) for i in range(0, len(items), per_line)]
    return "[\n" + "".join(f"{indent}{ln},\n" for ln in lines) + "]"


def source_block(file: str, repo: str, revision: str, symbol: str | None = None) -> str:
    """Provenance as one inline table, so it cannot capture the keys that follow it."""
    fields = [f"repository = {toml_str(repo)}", f"revision = {toml_str(revision)}", f"file = {toml_str(file)}"]
    if symbol:
        fields.append(f"symbol = {toml_str(symbol)}")
    return "source = { " + ", ".join(fields) + " }\n"


