#!/usr/bin/env python3
"""Generate the Phase 1 stat tables from the pinned L2J High Five source.

Reads two local clones at the pinned revisions (see packages/data/SOURCES.md):

    git clone -b develop https://bitbucket.org/l2jserver/l2j-server-game.git
    git clone -b develop https://bitbucket.org/l2jserver/l2j-server-datapack.git
    (checkout GAME_REVISION / DATAPACK_REVISION below)

and writes packages/data/tables/*.toml and packages/data/classes/*.toml:

    python3 packages/data/scripts/gen_tables.py --game PATH --datapack PATH [--check]

Every decimal is kept as its literal source string next to its exact scaled integer
(Q = 1_000_000). Arithmetic uses `decimal` / `fractions` only; no binary floating point
touches a value that is written out. Formula constants are not typed in here: each one is
parsed out of a literal source line that must exist verbatim in the pinned revision, so a
different revision fails loudly instead of drifting. `--check` regenerates in memory and
exits non-zero if any committed file differs.
"""

