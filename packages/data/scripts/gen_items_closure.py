#!/usr/bin/env python3
"""Generate tables-phase5/items_closure.toml (ruling D10) from the pinned item XML.

The 4,264 Phase 5 catalogue-closure templates (catalogue.toml `phase4_closure_additions`) have no
row in the V6 item bundle, and that bundle and its hash must not change. This table carries their
ItemDefinition rows (gen_items.project_item, the V6 row function, so the shapes cannot drift) and
their ItemCapability rows (gen_items.local_blockers plus the item-skill dependency rule, evaluated
against the committed V6 skill bundle as it is). Phase5Rules hashes it; V7 admits V6 items plus
these rows; V6 epochs never read it.

Storability: every closure row is storable (D5, E51: common, shadow and time-limited templates are
storable and keep their `context:*` blockers, which defer use only); the catalogue `not_storable`
list is empty and the generator refuses a non-empty one.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
import sys
import tomllib
from xml.parsers import expat

try:
    import gen_items
    import gen_skills
except ModuleNotFoundError:
    from packages.data.scripts import gen_items, gen_skills

ROOT = Path(__file__).resolve().parents[1]
OUT = 'tables-phase5/items_closure.toml'
# The V6 item bundle this table extends (Phase4Rules hash, every V6 recording binds it). The
# Phase5Rules loader (P5-D12, zone lane) is to check it; until it does, this script only checks
# that the committed V6 tables still carry the manifest data_sha256 that produced the table, and
# table freshness relies on `gen_items.py --check` in check_all.py (c-review-6 P3-5).
V6_ITEMS_SHA256 = 'bfee2e7d9fb73f53706c7a4afc19f5d095f4d630ca90e9a5747895c0e5472aad'
V6_MANIFEST_DATA_SHA256 = 'f0e8dc63a0aa8d013b5c4ecf2c0698d64438f914a2a9bc099b48651af9923b5e'
SUPPORTED_HANDLERS = {'', 'SoulShots', 'SpiritShot', 'BlessedSpiritShot', 'ItemSkills', 'ItemSkillsTemplate', 'EnchantScrolls',
                      'ManaPotion', 'Potion', 'Elixir', 'ScrollOfEscape', 'ScrollOfResurrection'}
HEADER = ['# GENERATED by packages/data/scripts/gen_items_closure.py from the pinned L2J High Five source',
          '# (packages/data/SOURCES.md). Do not edit by hand; regenerate instead.',
          '# D10: ItemDefinition and ItemCapability rows of the Phase 5 catalogue closure; the V6 bundle is unchanged.', '']


class SourceError(ValueError):
    """Missing, inconsistent or unsupported input."""


def load(rel: str, root: Path = ROOT) -> dict:
    return tomllib.loads((root / rel).read_text())


def v6_inputs(root: Path = ROOT):
    """The committed V6 item set, capability rows, skill bundle and policies (gen_items.py --check keeps them fresh)."""
    manifest = load('tables-phase4/rules_manifest.toml', root)
    if manifest['data_sha256'] != V6_MANIFEST_DATA_SHA256:
        raise SourceError('the V6 item bundle changed; the closure must not be regenerated against another V6 hash')
    items = set()
    for name in ('weapons', 'armors', 'etc_items'):
        items |= {row['template_id'] for row in load(f'tables-phase4/{name}.toml', root)['items']}
    caps = load('tables-phase4/capabilities.toml', root)
    skills = {row['id']: row for row in caps['skills']}
    skill_data = {}
    for path in sorted((root / 'skills-phase4').glob('*.toml')):
        data = tomllib.loads(path.read_text())
        skill_data[data['id']] = data
    policy = load('tables-phase4/capacities.toml', root)['policy']
    return items, {row['template_id']: row for row in caps['items']}, skills, skill_data, policy


def capability_rows(rows: dict, v6_caps: dict, skills: dict, skill_data: dict, policy: dict) -> list:
    """gen_items.capabilities() restricted to item rows, against the V6 skill bundle as committed."""
    def dependencies(refs):
        out = set()
        for ref in refs:
            skill = skills.get(ref['id'])
            if skill is None or not skill['admitted'] or not 1 <= ref['level'] <= skill['max_level']:
                out.add(f'skill:{ref["id"]}:{ref["level"]}')
        return out
    caps = []
    for sid, row in sorted(rows.items()):
        b = gen_items.local_blockers(row) | dependencies(row['skills'] + row['enchant4_skills'])
        if row['handler'] == 'ManaPotion' and policy['mana_potion_support'] == 'false':
            b.add('configuration:mana_potions_disabled')
        use = set()
        if row['handler'] not in SUPPORTED_HANDLERS:
            use.add('handler:' + row['handler'])
        if row['kind'] == 'EtcItem' and row['handler'] == '' and row['etcitem_type'] not in {'ARROW', 'BOLT'}:
            use.add('use:no_handler')
        if row['kind'] == 'EtcItem' and use and row['skills']:
            b.update(use)
        caps.append({'template_id': sid, 'admitted': not b, 'storable': True, 'blockers': sorted(b), 'use_blockers': sorted(b | use)})
    index = dict(v6_caps)
    index.update({row['template_id']: row for row in caps})
    consumables = {}
    for sid, row in sorted(rows.items()):
        required = []
        for ref in row['skills'] + row['enchant4_skills']:
            skill = skill_data.get(ref['id'], {})
            rank = ref['level']
            if not 1 <= rank <= skill.get('max_level', 0):
                continue
            for req in skill.get('item_consume', []):
                target = req['item_id'][rank - 1] if isinstance(req['item_id'], list) else req['item_id']
                count = req['count'][rank - 1] if isinstance(req['count'], list) else req['count']
                if target and count > 0:
                    required.append((target, f'consumable:skill:{ref["id"]}:{rank}:item:{target}'))
        consumables[sid] = required
    changed = True
    while changed:  # D54: deferral propagates through consumed items, including cycles
        changed = False
        for row in caps:
            b = {blocker for target, blocker in consumables[row['template_id']]
                 if target not in index or not index[target]['storable'] or not index[target]['admitted']}
            if b - set(row['blockers']) or (b and row['admitted']):
                changed = True
                row['admitted'] = False
                row['blockers'] = sorted(set(row['blockers']) | b)
                row['use_blockers'] = sorted(set(row['use_blockers']) | b)
    return caps


def generate(dp: Path = gen_items.DEFAULT_DP, game: Path = gen_items.DEFAULT_GAME, root: Path = ROOT):
    catalogue = load('tables-phase5/catalogue.toml', root)
    if catalogue['not_storable']:
        raise SourceError('catalogue not_storable is not empty; D5 storability is violated')
    wanted = set(catalogue['phase4_closure_additions'])
    if len(wanted) != len(catalogue['phase4_closure_additions']):
        raise SourceError('duplicate closure template')
    v6_items, v6_caps, skills, skill_data, policy = v6_inputs(root)
    overlap = wanted & v6_items
    if overlap:
        raise SourceError(f'closure templates already in the V6 bundle: {sorted(overlap)[:10]}')
    inputs = gen_items.Inputs(dp, game)
    slots = gen_items.java_slots(inputs)
    classifications = gen_items.java_classifications(inputs)
    rows, seen = {}, set()
    for path in sorted((dp / (gen_items.D + 'stats/items')).glob('*.xml')):
        file = path.relative_to(dp).as_posix()
        for node in gen_items.children(inputs.xml(file), 'item'):
            sid = int(gen_items.attrs(node)['id'])
            if sid in seen:
                raise SourceError(f'duplicate template {sid}')
            seen.add(sid)
            if sid in wanted:
                rows[sid] = gen_items.project_item(node, file, slots, classifications)
    missing = wanted - rows.keys()
    if missing:
        raise SourceError(f'closure templates missing from the pinned XML: {sorted(missing)[:10]}')
    referenced = {row['id'] for row in catalogue['templates']}
    uncovered = referenced - v6_items - rows.keys()
    if uncovered:
        raise SourceError(f'V6 plus closure does not cover the Phase 5 references: {sorted(uncovered)[:10]}')
    caps = capability_rows(rows, v6_caps, skills, skill_data, policy)
    sources = [gen_items.source(gen_items.G + 'model/items/' + file + '.java', lines, 'loader defaults', True)
               for file, lines in [('L2Item', '157-218,252-255,352-353'), ('L2EtcItem', '49-73')]]
    sources.append(gen_items.source(gen_items.D + 'stats/items/*.xml', '1-*', 'item templates'))
    sources += [{'repository': 'nightfall-rpg', 'revision': 'in-tree', 'file': f'packages/data/{rel}', 'lines': '1-*', 'symbol': symbol}
                for rel, symbol in [('tables-phase5/catalogue.toml', 'phase4_closure_additions'),
                                    ('tables-phase4/capabilities.toml', 'V6 skill bundle'),
                                    ('tables-phase4/rules_manifest.toml', 'V6 item bundle')]]
    data = {'schema_version': 1, 'sources': sources, 'v6_items_sha256': V6_ITEMS_SHA256,
            'items': [row for _, row in sorted(rows.items())], 'capabilities': caps}
    lines = list(HEADER)
    gen_skills.emit_fields(lines, data)
    content = '\n'.join(lines) + '\n'
    if tomllib.loads(content) != data:
        raise SourceError('TOML changed structure')
    gen_items.canonical(data)  # refuses any binary float
    counts = {'items': len(rows), 'admitted': sum(r['admitted'] for r in caps), 'deferred': sum(not r['admitted'] for r in caps),
              'storable': sum(r['storable'] for r in caps), 'phase5_references': len(referenced)}
    return content, counts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--datapack', type=Path, default=gen_items.DEFAULT_DP)
    parser.add_argument('--game', type=Path, default=gen_items.DEFAULT_GAME)
    parser.add_argument('--out', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        content, counts = generate(args.datapack, args.game)
    except (ValueError, OSError, KeyError, expat.ExpatError, subprocess.CalledProcessError, gen_skills.SourceError) as error:
        print('gen_items_closure: ' + str(error), file=sys.stderr)
        return 2
    path = args.out / OUT
    if args.check:
        if not path.exists() or path.read_text() != content:
            print('gen_items_closure: stale: ' + OUT, file=sys.stderr)
            return 1
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    print('gen_items_closure: ' + json.dumps(counts, sort_keys=True))
    print('gen_items_closure: ' + ('check passed' if args.check else 'generated'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
