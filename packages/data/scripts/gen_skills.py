def param_allowed(value: str, rule) -> bool:
    if isinstance(rule, set):
        return value in rule
    if rule == "bool":
        return value in {"true", "false"}
    if rule in {"int", "positive_int"}:
        return bool(re.fullmatch(r"[+-]?\d+", value)) and (rule != "positive_int" or int(value) > 0)
    if rule == "number":
        try:
            return bool(re.fullmatch(r"[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?", value)) and Decimal(value).is_finite()
        except InvalidOperation:
            return False
    if rule == "dispel":
        return all(parts[0] in DISPEL_SLOTS and (len(parts) == 1 or
                   (len(parts) == 2 and param_allowed(parts[1], "int")))
                   for entry in value.split(";") for parts in [entry.split(",")])
    return False


def load_all_datapack_skills(dp: Datapack, phase4: bool = False) -> dict[int, tuple[str, ET.Element]]:
    skills = {}
    skills_dir = dp.root / DATA_STATS_SKILLS
    for xml_path in sorted(skills_dir.rglob("*.xml") if phase4 else skills_dir.glob("*.xml")):
        tree = ET.parse(xml_path)
        for s in tree.getroot().iter("skill"):
            sid = int(s.attrib["id"])
            rel_file = xml_path.relative_to(dp.root).as_posix()
            skills[sid] = (rel_file, s)
    return skills


def compute_all_blockers(
    all_dp_skills: dict[int, tuple[str, ET.Element]],
    target_ids: set[int],
    phase4: bool = False,
) -> tuple[set[int], dict[int, set[str]]]:
    allowed_stats = ALLOWED_STATS | (PHASE4_STATS if phase4 else set())
    allowed_effects = TIER_B_EFFECTS | (set(PHASE4_EFFECT_PARAMS) if phase4 else set())
    skill_tables: dict[int, dict[str, list[str]]] = {}
    for sid in all_dp_skills:
        skill_tables[sid] = parse_tables(all_dp_skills[sid][1])

    # Transitive closure
    discovered = set(target_ids)
    frontier = set(target_ids)
    while frontier:
        next_frontier = set()
        for sid in frontier:
            if sid in all_dp_skills:
                _, s = all_dp_skills[sid]
                for r in get_referenced_skills(s, skill_tables[sid]):
                    if r not in discovered:
                        discovered.add(r)
                        next_frontier.add(r)
        frontier = next_frontier

    initial_blockers: dict[int, set[str]] = {}
    for sid in discovered:
        if sid not in all_dp_skills:
            initial_blockers[sid] = {f"ref:{sid}"}
            continue
        rel_file, s = all_dp_skills[sid]
        blockers = set()
        tables = skill_tables[sid]

        sets: dict[str, str | list[str]] = {}
        for elem in s.findall("set"):
            name = elem.attrib.get("name", "")
            val = elem.attrib.get("val", "")
            sets[name] = expand(val, tables, int(s.attrib.get("levels", 1))) if val.startswith("#") else val

        op_type = sets.get("operateType", "unset")
        for op in set(op_type if isinstance(op_type, list) else [op_type]):
            if op not in ALLOWED_OPERATE_TYPES:
                blockers.add(f"operate:{op}")

        tgt = sets.get("targetType", "unset")
        for t in set(tgt if isinstance(tgt, list) else [tgt]):
            item_selector_noop = (phase4 and t == "NONE" and sets.get("isMagic") == "2"
                and not any(child.tag.endswith("ffects") and child.findall("effect") for child in s))
            if t not in ALLOWED_TARGET_TYPES and not item_selector_noop:
                blockers.add(f"target:{t}")

        scope = sets.get("affectScope", "unset")
        for sc in set(scope if isinstance(scope, list) else [scope]):
            if sc not in ALLOWED_AFFECT_SCOPES | ({"FAN"} if phase4 else set()):
                blockers.add(f"scope:{sc}")

        has_item_consume = False
        for k in sets:
            if "itemconsume" in k.lower():
                vals = sets[k] if isinstance(sets[k], list) else [sets[k]]
                if any(v not in ("0", 0, None) for v in vals):
                    has_item_consume = True
        if has_item_consume and not phase4:
            blockers.add("item_consume")

        for cond in s.findall("cond"):
            blockers.update(get_cond_blockers(cond, phase4))

        affect_object = sets.get("affectObject")
        if affect_object is not None:
            for value in affect_object if isinstance(affect_object, list) else [affect_object]:
                if value not in ALLOWED_AFFECT_OBJECTS:
                    blockers.add(f"scope_filter:{value}")

        for child in s:
            if child.tag.endswith("ffects") and not child.tag.startswith("enchant"):
                if child.tag != "effects":
                    blockers.add(f"section:{child.tag}")
                for cond in condition_nodes(child):
                    blockers.update(get_cond_blockers(cond, phase4))
                for eff in child.findall("effect"):
                    for cond in condition_nodes(eff):
                        blockers.update(get_cond_blockers(cond, phase4))
                    name = eff.attrib.get("name", "")
                    if name in ("TargetMe", "TickHpFatal"):
                        blockers.add(f"effect:{name}")
                    elif name not in allowed_effects:
                        blockers.add(f"effect:{name}")

                    levels = int(s.attrib.get("levels", 1))
                    if name in allowed_effects:
                        params = effect_params(eff)
                        rules = (EFFECT_PARAMS | (PHASE4_EFFECT_PARAMS if phase4 else {})).get(name, {})
                        for key, val in params.items():
                            values = expand(val, tables, levels)
                            if key not in rules or not all(param_allowed(v, rules[key]) for v in values):
                                blockers.add(f"param:{name}.{key}")
                        if name in {"TickHp", "TickMp"} and "ticks" not in params:
                            blockers.add(f"param:{name}.ticks")
                    for stat_elem in eff:
                        if stat_elem.tag in ALL_STAT_OPS:
                            for cond in condition_nodes(stat_elem):
                                blockers.update(get_cond_blockers(cond, phase4))
                            for attr in set(stat_elem.attrib) - ALLOWED_STAT_ATTRIBUTES[stat_elem.tag]:
                                blockers.add(f"stat_attr:{attr}")
                            if stat_elem.tag not in ALLOWED_STAT_OPS:
                                blockers.add(f"op:{stat_elem.tag}")
                            stat_name = stat_elem.attrib.get("stat", "")
                            if stat_name not in allowed_stats:
                                blockers.add(f"stat:{stat_name}")
                            if not all(param_allowed(v, "number") for v in expand(stat_elem.get("val", ""), tables, levels)):
                                blockers.add(f"stat_value:{stat_name}")

        initial_blockers[sid] = blockers

    # Propagate blockers from referenced skills
    changed = True
    while changed:
        changed = False
        for sid in sorted(discovered):
            if sid in all_dp_skills:
                _, s = all_dp_skills[sid]
                for ref_sid in get_referenced_skills(s, skill_tables[sid]):
                    if ref_sid in initial_blockers and initial_blockers[ref_sid]:
                        ref_blocker = f"ref:{ref_sid}"
                        if ref_blocker not in initial_blockers[sid]:
                            initial_blockers[sid].add(ref_blocker)
                            changed = True

    return discovered, initial_blockers


def generate_skill_toml(
    sid: int,
    rel_file: str,
    s: ET.Element,
    blockers: set[str],
    is_sample_only: bool = False,
    phase4: bool = False,
) -> str:
    levels = int(s.attrib.get("levels", 1))
    tables = parse_tables(s)
    raw_sets = {e.attrib["name"]: e.attrib["val"] for e in s.findall("set")}

    def resolved(value: str, convert=str, force_array=False):
        vals = expand(value, tables, levels)
        converted = [convert(v) for v in vals]
        return converted if force_array or value.startswith("#") else converted[0]

    def field(key: str, default, convert=str, force_array=False):
        return resolved(raw_sets.get(key, str(default)), convert, force_array)

    condition_tables = {}

    def conditions(elem: ET.Element) -> dict:
        conds = condition_elements(elem)
        result = {}
        if conds:
            for cond in conds:
                for node in cond.iter():
                    for value in node.attrib.values():
                        if value.startswith("#"):
                            condition_tables[value] = expand(value, tables, levels)
            result["raw_conditions"] = [re.sub(r">\s+<", "><", ET.tostring(c, encoding="unicode").strip()) for c in conds]
            result["conditions"] = [parse_cond_node(ch, phase4) for ch in condition_nodes(elem)]
        return result

    boolean = lambda v: v.lower() == "true"  # StatsSet/Boolean.parseBoolean semantics
    data = {
        "provenance": {"repository": DATAPACK_REPOSITORY, "revision": DATAPACK_REVISION,
                       "file": rel_file, "skill_id": sid},
        "id": sid, "key": f"l2.skill.{sid}", "l2_ref": s.attrib.get("name", ""),
        "max_level": levels, "operate_type": field("operateType", "unset"),
        "is_magic": field("isMagic", 0, int),
        "target_type": field("targetType", "unset"),
        "affect_scope": field("affectScope", "unset"),
    }
    for key, dest in [("affectRange", "affect_range"), ("affectObject", "affect_object")]:
        if key in raw_sets:
            data[dest] = field(key, "", int if key == "affectRange" else str)
    if "affectLimit" in raw_sets:
        def limit(v):
            parts = v.split("-")
            return {"offset": int(parts[0]), "width": int(parts[1]) if len(parts) > 1 else 0}
        data["affect_limit"] = field("affectLimit", "0", limit)
    for key, dest, default in [
        ("castRange", "cast_range", -1), ("effectRange", "effect_range", -1),
        ("hitTime", "hit_time_ms", 0), ("coolTime", "cool_time_ms", 0),
        ("reuseDelay", "reuse_ms", 0), ("hitCancelTime", "hit_cancel_ms", 0),
        ("activateRate", "activate_rate", -1), ("lvlBonusRate", "level_bonus_rate", 0),
        ("minChance", "min_chance", 10), ("maxChance", "max_chance", 90),
    ]:
        data[dest] = field(key, default, int)
    data["reuse_delay_lock"] = field("reuseDelayLock", "false", boolean)
    for key, dest in [("mpConsume1", "mp_consume_start"),
                      ("mpConsume2" if "mpConsume2" in raw_sets else "mpConsume", "mp_consume_end"),
                      ("hpConsume", "hp_consume"), ("magicLvl", "magic_level"), ("effectPoint", "effect_point")]:
        data[dest] = field(key, 0, int, True)
    data.update({"basic_property": field("basicProperty", "NONE"), "trait": field("trait", "NONE"),
                 "next_action_attack": field("nextActionAttack", "false", boolean),
                 "has_enchant_routes": any(k.startswith("enchantGroup") for k in s.attrib),
                 "runtime_status": "deferred" if blockers else "executable", "blockers": sorted(blockers)})
    # Skill.java:231-232,300 and 479-487. Damage/action flags are derived
    # from abnormalType, not XML bool attributes. Keep source rank semantics.
    for source_key, output_key, default in [
        ("stayAfterDeath", "stay_after_death", "false"),
        ("stayOnSubclassChange", "stay_on_subclass_change", "true"),
        ("irreplaceableBuff", "irreplaceable_buff", "false"),
        ("abnormalInstant", "abnormal_instant", "false"),
    ]:
        data[output_key] = field(source_key, default, boolean)
    data["removed_on_damage"] = field("abnormalType", "NONE", lambda v: v in {"SLEEP", "FORCE_MEDITATION", "HIDE"})
    data["removed_on_action_except_move"] = field("abnormalType", "NONE", lambda v: v in {"INVINCIBILITY", "HIDE"})
    if is_sample_only:
        data["sample_only"] = True
    data.update(conditions(s))
    data["attribute"] = {"type": field("attributeType", "NONE"), "power": field("attributePower", 0, int)}
    if any(k in raw_sets for k in ("abnormalType", "abnormalTime", "abnormalVisualEffect")) or raw_sets.get("isDebuff") == "true":
        data["abnormal"] = {"type": field("abnormalType", "NONE"), "level": field("abnormalLvl", 0, int, True),
                            "time_s": field("abnormalTime", 0, int, True), "is_debuff": field("isDebuff", "false", boolean)}
        if "abnormalVisualEffect" in raw_sets:
            data["abnormal"]["visual"] = field("abnormalVisualEffect", "")
    if "itemConsumeId" in raw_sets and "itemConsumeCount" in raw_sets:
        data["item_consume"] = [{"item_id": field("itemConsumeId", 0, int), "count": field("itemConsumeCount", 0, int)}]
    # Keep all source sets as exact strings (and expand every table, including
    # fields outside the executable slice). No unresolved #reference can escape.
    data["source_sets"] = {k: resolved(v) for k, v in sorted(raw_sets.items())}
    effects = []
    for sec in s:
        if sec.tag.endswith("ffects") and not sec.tag.startswith("enchant"):
            for eff in sec.findall("effect"):
                params = effect_params(eff)
                if eff.get("name") in {"TickHp", "TickMp"}:
                    params.setdefault("mode", "DIFF")
                entry = {"section": sec.tag, "name": eff.get("name", ""),
                         "params": {k: resolved(v) for k, v in sorted(params.items())}}
                entry.update(conditions(eff))
                section_conds = conditions(sec)
                entry.update({"section_" + k: v for k, v in section_conds.items()})
                stats = []
                for ch in eff:
                    if ch.tag in ALL_STAT_OPS:
                        stat = {"op": ch.tag, "stat": ch.get("stat", ""), "value": resolved(ch.get("val", ""), force_array=True)}
                        if set(ch.attrib) - ALLOWED_STAT_ATTRIBUTES[ch.tag]:
                            stat["raw_attributes"] = dict(ch.attrib)
                        if "order" in ch.attrib:
                            stat["order"] = resolved(ch.attrib["order"], int)
                        stat.update(conditions(ch))
                        stats.append(stat)
                entry["stat_children"] = stats
                effects.append(entry)
    data["effects"] = effects
    if condition_tables:
        # Values are indexed by skill level - 1; normalized refs retain their exact XML names.
        data["condition_tables"] = dict(sorted(condition_tables.items()))
    lines = [SKILL_HEADER.rstrip(), ""]
    if is_sample_only:
        lines.append("# Out-of-scope sample only; do not ship in runtime registry.")
    emit_fields(lines, data)
    if phase4:
        lines.insert(1, "# V6-only capability contract; historical skills/ files are unchanged.")
    content = "\n".join(lines).rstrip() + "\n"
    # Syntax AND structure validated before writing, including --check.
    if tomllib.loads(content) != data:
        raise SourceError(f"skill {sid}: TOML serialization changed the parsed structure")
    return content


def generate_catalog_toml(
    catalog_skills: list[dict],
    skill_blockers: dict[int, set[str]],
) -> str:
    out = CATALOG_HEADER
    for entry in sorted(catalog_skills, key=lambda s: s["id"]):
        sid = entry["id"]
        status = "deferred" if skill_blockers.get(sid) else "executable"
        out += "\n[[skills]]\n"
        out += f"id = {sid}\n"
        out += f'key = "{entry["key"]}"\n'
        out += f"max_level = {entry['max_level']}\n"
        out += f'l2_ref = "{entry["l2_ref"]}"\n'
        out += f'source_file = "{entry["source_file"]}"\n'
        out += f'runtime_status = "{status}"\n'
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--datapack", type=Path, default=DEFAULT_DATAPACK_PATH, help="l2j-server-datapack clone")
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--check", action="store_true", help="fail if committed files differ")
    args = parser.parse_args()

    try:
        dp = Datapack(args.datapack)
    except SourceError as err:
        print(f"gen_skills: {err}", file=sys.stderr)
        return 2

    # Load skill_catalog.toml
    catalog_path = args.out / "skill_catalog.toml"
    with open(catalog_path, "rb") as f:
        catalog_data = tomllib.load(f)
    catalog_skills = catalog_data.get("skills", [])
    catalog_ids = {s["id"] for s in catalog_skills}

    # Target IDs: 378 catalog skills + 5076 + 286 (sample)
    target_ids = set(catalog_ids) | {5076, 286}

    all_dp_skills = load_all_datapack_skills(dp)
    discovered_ids, all_blockers = compute_all_blockers(all_dp_skills, target_ids)

    # Generate skills and catalog files
    files: dict[str, str] = {}
    for sid in sorted(discovered_ids):
        if sid in all_dp_skills:
            rel_file, s_elem = all_dp_skills[sid]
            files[f"skills/{sid}.toml"] = generate_skill_toml(
                sid,
                rel_file,
                s_elem,
                all_blockers.get(sid, set()),
                is_sample_only=(sid == 286),
            )

    files["skill_catalog.toml"] = generate_catalog_toml(catalog_skills, all_blockers)

    stale: list[str] = []
    if args.check:
        skills_dir = args.out / "skills"
        for p in sorted(skills_dir.glob("*.toml")):
            rel = p.relative_to(args.out).as_posix()
            if rel not in files:
                stale.append(f"unexpected file: {rel}")

    for rel, content in sorted(files.items()):
        path = args.out / rel
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(rel)
        elif not path.exists() or path.read_text(encoding="utf-8") != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    if stale:
        print("gen_skills: stale generated files: " + ", ".join(stale[:10]), file=sys.stderr)
        if len(stale) > 10:
            print(f"... and {len(stale) - 10} more", file=sys.stderr)
        return 1

    # Exact counts report
    cat_exec = [sid for sid in catalog_ids if not all_blockers[sid]]
    cat_def = [sid for sid in catalog_ids if all_blockers[sid]]
    total_exec = [sid for sid in discovered_ids if not all_blockers[sid]]
    total_def = [sid for sid in discovered_ids if all_blockers[sid]]

    print(f"gen_skills: {len(discovered_ids)} total skills parsed ({len(total_exec)} executable, {len(total_def)} deferred)")
    print(f"gen_skills: {len(catalog_ids)} catalog skills ({len(cat_exec)} executable, {len(cat_def)} deferred)")

    # Print top blockers in catalog
    blocker_counter: collections.Counter = collections.Counter()
    for sid in catalog_ids:
        for b in all_blockers[sid]:
            blocker_counter[b] += 1
    print("\nTop blockers across catalogue:")
    for b, cnt in blocker_counter.most_common(15):
        print(f"  {b}: {cnt}")

    # Per populated tree breakdown
    print("\nPer-tree executability:")
    for prof_path in sorted(glob.glob(str(args.out / "professions/*.toml"))):
        with open(prof_path, "rb") as pf:
            pdata = tomllib.load(pf)
        if pdata.get("skill_tree_status") == "populated":
            tree_sids = {row["skill_id"] for row in pdata.get("skill_tree", [])}
            ex_cnt = sum(1 for sid in tree_sids if not all_blockers[sid])
            def_cnt = len(tree_sids) - ex_cnt
            pname = Path(prof_path).stem
            print(f"  {pname}: {len(tree_sids)} skills ({ex_cnt} exec, {def_cnt} def)")

    status_label = "check passed" if args.check else "generated successfully"
    print(f"\ngen_skills: {status_label}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except SourceError as err:
        print(f"gen_skills: {err}", file=sys.stderr)
        sys.exit(2)
