class SourceError(Exception):
    """Raised when the pinned source inputs cannot be admitted."""


class Datapack:
    def __init__(self, root: Path) -> None:
        try:
            head = subprocess.run(
                ["git", "-C", str(root), "rev-parse", "HEAD"],
                check=True,
                capture_output=True,
                text=True,
            ).stdout.strip()
        except Exception as exc:
            raise SourceError(f"failed to check git revision of {root}: {exc}") from exc

        if head != DATAPACK_REVISION:
            raise SourceError(f"datapack clone is at {head}, expected pinned {DATAPACK_REVISION}")

        dirty = subprocess.run(
            ["git", "-C", str(root), "status", "--porcelain", "--untracked-files=all", "--ignored=matching", "--",
             DATA_STATS_SKILLS, LEARNING_SOURCE],
            check=True, capture_output=True, text=True,
        ).stdout.strip()
        if dirty:
            raise SourceError(f"datapack source inputs are dirty at pinned revision: {dirty}")
        self.root = root

    def read_xml(self, subpath: str) -> ET.Element:
        path = self.root / subpath
        if not path.is_file():
            raise SourceError(f"missing expected datapack file: {path}")
        return ET.parse(path).getroot()


def parse_tables(skill_elem: ET.Element) -> dict[str, list[str]]:
    tables: dict[str, list[str]] = {}
    for t in skill_elem.findall("table"):
        name = t.attrib["name"]
        tables[name] = t.text.split() if t.text else []
    return tables


def get_referenced_skills(skill_elem: ET.Element, tables: dict[str, list[str]]) -> set[int]:
    refs = set()
    for e in skill_elem.iter("param"):
        for k, v in e.attrib.items():
            if "skillid" in k.lower():
                val_list = expand(v, tables, int(skill_elem.get("levels", "1")))
                for item in val_list:
                    try:
                        iv = int(item)
                        if iv > 0:
                            refs.add(iv)
                    except ValueError:
                        pass
    return refs


def is_cond_allowed(elem: ET.Element, phase4: bool = False) -> bool:
    if elem.tag in ("and", "or", "not"):
        return not elem.attrib and all(is_cond_allowed(child, phase4) for child in elem)
    if phase4:
        if elem.tag == "player" and set(elem.attrib) == {"insideZoneId"}:
            return all(param_allowed(part.strip(), "positive_int") for part in elem.attrib["insideZoneId"].split(","))
        if elem.tag == "player" and set(elem.attrib) in ({"resting"}, {"standing"}, {"moving"}, {"running"}, {"canEscape"}, {"flyMounted"}):
            return next(iter(elem.attrib.values())) in {"true", "false"}
        if elem.tag == "using" and set(elem.attrib) == {"slot"}:
            return elem.attrib["slot"] in {"chest", "lhand", "rhand", "lrhand", "head", "legs", "feet", "gloves"}
        if elem.tag == "player" and set(elem.attrib) in ({"weight"}, {"invSize"}):
            return param_allowed(next(iter(elem.attrib.values())), "int")
    if elem.tag == "using":
        return (set(elem.attrib) == {"kind"}
                and all(k.strip() in (ALLOWED_WEAPON_KINDS | ({"LIGHT", "MAGIC", "HEAVY", "SIGIL", "SHIELD"} if phase4 else set())) for k in elem.attrib["kind"].split(",")))
    if elem.tag == "player":
        if set(elem.attrib.keys()) == {"canResurrect"} and elem.attrib["canResurrect"] in {"true", "false"}:
            return True
    return False


def cond_sig(e: ET.Element) -> str:
    attrs = ",".join(sorted(e.attrib.keys()))
    return f"{e.tag}:{attrs}" if attrs else e.tag


def condition_elements(elem: ET.Element) -> list[ET.Element]:
    if elem.tag == "skill":
        return elem.findall("cond")
    if elem.tag.endswith("ffects"):
        return [ch for ch in elem if ch.tag != "effect"]
    if elem.tag == "effect":
        return [ch for ch in elem if ch.tag not in ALL_STAT_OPS | {"param"}]
    return list(elem)  # stat children contain bare conditions as well as <cond>


def condition_nodes(elem: ET.Element) -> list[ET.Element]:
    return [node for c in condition_elements(elem) for node in (list(c) if c.tag == "cond" else [c])]


def get_cond_blockers(cond_elem: ET.Element, phase4: bool = False) -> set[str]:
    blockers: set[str] = set()

    def walk(e: ET.Element) -> None:
        if e.tag in ("and", "or", "not", "cond"):
            if e.tag != "cond" and e.attrib:
                blockers.add(f"cond:{cond_sig(e)}")
            for c in e:
                walk(c)
        elif e.tag == "using" and set(e.attrib) == {"kind"}:
            for value in e.attrib["kind"].split(","):
                if value.strip() not in ALLOWED_WEAPON_KINDS | ({"LIGHT", "MAGIC", "HEAVY", "SIGIL", "SHIELD"} if phase4 else set()):
                    blockers.add(f"cond:using_kind:{value.strip()}")
        elif not is_cond_allowed(e, phase4):
            blockers.add(f"cond:{cond_sig(e)}")

    walk(cond_elem)
    return blockers


def parse_cond_node(elem: ET.Element, phase4: bool = False) -> dict:
    if phase4 and is_cond_allowed(elem, phase4):
        if elem.tag == "player" and set(elem.attrib) == {"insideZoneId"}:
            return {"kind": "player_inside_zone_ids", "zone_ids": [int(part.strip()) for part in elem.attrib["insideZoneId"].split(",")]}
        if elem.tag == "player" and set(elem.attrib) in ({"resting"}, {"standing"}, {"moving"}, {"running"}, {"canEscape"}, {"flyMounted"}):
            key = next(iter(elem.attrib))
            return {"kind": "player_" + key, "value": elem.attrib[key] == "true"}
        if elem.tag == "using" and "slot" in elem.attrib:
            return {"kind": "using_slot", "slot": elem.attrib["slot"]}
        if elem.tag == "player" and set(elem.attrib) in ({"weight"}, {"invSize"}):
            key = next(iter(elem.attrib))
            return {"kind": "player_" + key, "value": int(elem.attrib[key])}
    if elem.tag == "using" and is_cond_allowed(elem, phase4):
        kinds = [k.strip() for k in elem.attrib["kind"].split(",")]
        return {"kind": "using_kind", "weapon_kinds": kinds}
    elif elem.tag == "player" and is_cond_allowed(elem):
        return {"kind": "player_can_resurrect", "value": elem.attrib["canResurrect"] == "true"}
    elif elem.tag in ("and", "or", "not"):
        node = {"kind": elem.tag, "conditions": [parse_cond_node(c, phase4) for c in elem]}
        if elem.attrib:
            node["attrs"] = dict(elem.attrib)
        return node
    else:
        return {"kind": "unsupported", "tag": elem.tag, "attrs": dict(elem.attrib)}


def toml_value(value) -> str:
    """Encode inline values; nested condition/stat lists use array-of-table headers."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{toml_key(k)} = {toml_value(v)}" for k, v in value.items()) + " }"
    raise SourceError(f"unsupported TOML value: {value!r}")


def toml_key(key: str) -> str:
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else json.dumps(key)


def emit_fields(lines: list[str], obj: dict, path: str = "") -> None:
    # Write local scalars before nested arrays so TOML table scope cannot leak.
    arrays = []
    for key, val in obj.items():
        if isinstance(val, list) and val and isinstance(val[0], dict):
            arrays.append((key, val))
        else:
            lines.append(f"{toml_key(key)} = {toml_value(val)}")
    for key, vals in arrays:
        child_path = f"{path}.{toml_key(key)}" if path else toml_key(key)
        for val in vals:
            lines.extend(["", f"[[{child_path}]]"])
            emit_fields(lines, val, child_path)


def expand(value: str, tables: dict[str, list[str]], levels: int) -> list[str]:
    if not value.startswith("#"):
        return [value] * levels
    if value not in tables:
        raise SourceError(f"unresolved table reference {value}")
    vals = tables[value]
    if len(vals) != levels:
        raise SourceError(f"table {value} has {len(vals)} rows, expected {levels}")
    if any(v.startswith("#") for v in vals):
        raise SourceError(f"unresolved table reference inside {value}")
    return vals.copy()


def effect_params(eff: ET.Element) -> dict[str, str]:
    params = {k: v for p in eff.findall("param") for k, v in p.attrib.items()}
    params.update({k: v for k, v in eff.attrib.items() if k != "name"})
    return params


