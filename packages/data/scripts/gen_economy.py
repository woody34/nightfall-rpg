    tree = ET.parse(recipe_file)
    root = tree.getroot()
    
    recipes = []
    rare_count = 0
    
    for r in root.findall("item"):
        rid = int(r.get("id"))
        recipe_id = int(r.get("recipeId"))
        craft_level = int(r.get("craftLevel"))
