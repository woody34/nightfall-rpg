def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--datapack", type=Path, required=True, help="l2j-server-datapack clone")
    parser.add_argument("--game", type=Path, required=True, help="l2j-server-game clone")
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--check", action="store_true", help="fail if committed files differ")
    parser.add_argument(
        "--stories",
        type=str,
        default="1.1,1.2,1.3",
        help="comma-separated list of stories to generate (1.1, 1.2, 1.3)",
    )
    args = parser.parse_args()

    try:
        check_repo(args.datapack, DATAPACK_REVISION, "datapack")
        check_repo(args.game, GAME_REVISION, "game")
    except SourceError as err:
        print(f"gen_economy: {err}", file=sys.stderr)
        return 2

    stories = [s.strip() for s in args.stories.split(",") if s.strip()]
    
    data_dir = Path(__file__).resolve().parent.parent
    try:
        files = generate(args.datapack, args.game, data_dir, stories)
    except SourceError as err:
        print(f"gen_economy: {err}", file=sys.stderr)
        return 2

    stale = []
    for rel, content in sorted(files.items()):
        path = args.out / rel
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    if stale:
        print("gen_economy: stale generated files: " + ", ".join(stale), file=sys.stderr)
        return 1

    action = "verified" if args.check else "generated"
    print(f"gen_economy: {len(files)} files {action} successfully for stories {','.join(stories)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
