class SourceError(Exception):
    """The source clone is missing or does not match pinned revision."""


def check_repo(root: Path, revision: str, label: str) -> None:
    res = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
    )
    if res.returncode != 0:
        raise SourceError(f"Failed to check git revision for {label} at {root}: {res.stderr}")
    head = res.stdout.strip()
    if head != revision:
        raise SourceError(f"{label} clone at {root} has revision {head}, expected pinned {revision}")


def fl_bits(val: str | float) -> str:
    """Format IEEE-754 binary64 bit pattern as 16-character lowercase hex string."""
    return struct.pack(">d", float(val)).hex()


