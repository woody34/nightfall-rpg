#!/usr/bin/env python3
"""Generate tables-phase5/merchant_fixtures.toml (ruling P5-D29) for the Phase 5 fixture zone.

The V7 bootstrap spawns each row as a non-combat fixture NPC (speed 0, the D58 blacksmith
pattern), and the engine resolves a merchant by its entity name and exact position
(`Phase5Rules::merchant_fixture`). A row is `{npc, name, x, y}`:
- `npc` is a pinned NPC id that a merchants.toml buylist or a multisell.toml list names;
- `name` is the fixture display name: one token (the bot splits on whitespace), unique;
- `x`, `y` are whole tiles inside the zone bounds, on a free tile: not a zone fixture, the safe
  point, a spawn slot home, the Phase 4 blacksmith or another row.

The rows are the merchants of the phase5-vendors, phase5-vendor-restock and phase5-multisell packs
(apps/client-unreal/Scripts/phase5-expectations.py), within m(150) = 4,687 millitiles of the role
position (100, 100). Every row cites its pinned NPC template line.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import tomllib

try:
    import gen_items
except ModuleNotFoundError:
    from packages.data.scripts import gen_items

ROOT = Path(__file__).resolve().parents[1]
OUT = 'tables-phase5/merchant_fixtures.toml'
# (pinned npc, fixture name, x, y), and the pack that uses the row.
FIXTURES = [
    (31413, 'merchant', 101, 102, 'phase5-vendors'),
    (32347, 'exchanger', 101, 98, 'phase5-multisell'),
    (35363, 'restock_merchant', 99, 102, 'phase5-vendor-restock'),
]
ROLE = (100, 100)
VENDOR_RANGE_MILLITILES = 4687
HEADER = ['# GENERATED by packages/data/scripts/gen_merchant_fixtures.py from tables-phase5/merchants.toml,',
          '# tables-phase5/multisell.toml, zones/test_zone.toml and the pinned L2J High Five NPC templates',
          '# (packages/data/SOURCES.md). Do not edit by hand; regenerate instead.',
          '# P5-D29: the merchant fixture NPCs that the V7 bootstrap spawns in the Phase 5 test zone.', '']


class SourceError(ValueError):
    """Missing, inconsistent or unsupported input."""


def npc_line(dp: Path, npc: int) -> tuple[str, int, str]:
    """The pinned template file, line and name of `npc`."""
    folder = dp / 'src/main/resources/data/stats/npcs'
    for path in sorted(folder.glob('*.xml')):
        for number, line in enumerate(path.read_text().splitlines(), start=1):
            if f'<npc id="{npc}"' in line:
                name = line.split('name="', 1)[1].split('"', 1)[0]
                return str(path.relative_to(dp)), number, name
    raise SourceError(f'npc {npc} is not a pinned template')


def occupied(root: Path) -> set[tuple[int, int]]:
    zone = tomllib.loads((root / 'zones/test_zone.toml').read_text())
    taken = {tuple(n['pos']) for n in zone.get('npcs', [])}
    taken |= {tuple(s['home']) for s in zone.get('spawn_slots', [])}
    taken.add(tuple(zone['safe_point']['pos']))
    smith = tomllib.loads((root / 'tables-phase4/capacities.toml').read_text())['blacksmith']
    taken.add((smith['x'], smith['y']))
    return taken


def generate(dp: Path = gen_items.DEFAULT_DP, root: Path = ROOT):
    merchants = tomllib.loads((root / 'tables-phase5/merchants.toml').read_text())
    multisell = tomllib.loads((root / 'tables-phase5/multisell.toml').read_text())
    buylist_npcs = {row['npc'] for row in merchants['buylists']}
    multisell_npcs = {npc for row in multisell['list'] for npc in row.get('npcs', [])}
    zone = tomllib.loads((root / 'zones/test_zone.toml').read_text())
    (x0, y0), (x1, y1) = zone['bounds']['min'], zone['bounds']['max']
    taken = occupied(root)
    rows, sources, seen = [], [], set()
    for npc, name, x, y, pack in sorted(FIXTURES):
        if npc not in buylist_npcs | multisell_npcs:
            raise SourceError(f'npc {npc} has no buylist and no multisell list')
        if not name or any(c.isspace() for c in name) or name in {r['name'] for r in rows}:
            raise SourceError(f'npc {npc}: the name {name!r} is not one unique token')
        if not (x0 <= x <= x1 and y0 <= y <= y1) or (x, y) in taken or (x, y) in seen:
            raise SourceError(f'npc {npc}: ({x}, {y}) is not a free tile in the zone')
        dx, dy = (x - ROLE[0]) * 1000, (y - ROLE[1]) * 1000
        if dx * dx + dy * dy > VENDOR_RANGE_MILLITILES ** 2:
            raise SourceError(f'npc {npc}: ({x}, {y}) is out of m(150) of the role position')
        seen.add((x, y))
        rel, line, pinned = npc_line(dp, npc)
        rows.append({'npc': npc, 'name': name, 'x': x, 'y': y})
        sources.append({'repository': gen_items.gen_skills.DATAPACK_REPOSITORY, 'revision': gen_items.DATAPACK_REVISION,
                        'file': rel, 'line': line, 'npc': npc, 'pinned_name': pinned, 'pack': pack,
                        'buylist': npc in buylist_npcs, 'multisell': npc in multisell_npcs})
    lines = list(HEADER)
    lines.append('sources = [')
    for src in sources:
        lines.append('  ' + toml_inline(src) + ',')
    lines += [']', 'schema_version = 1', '']
    for row in rows:
        lines += ['[[merchants]]', f'npc = {row["npc"]}', f'name = "{row["name"]}"', f'x = {row["x"]}', f'y = {row["y"]}', '']
    content = '\n'.join(lines).rstrip('\n') + '\n'
    if tomllib.loads(content)['merchants'] != rows:
        raise SourceError('the table does not round-trip')
    return content, {'merchants': [(r['npc'], r['name'], r['x'], r['y']) for r in rows]}


def toml_inline(value: dict) -> str:
    def one(v):
        if isinstance(v, bool):
            return 'true' if v else 'false'
        if isinstance(v, int):
            return str(v)
        return json.dumps(v)
    return '{ ' + ', '.join(f'{k} = {one(v)}' for k, v in value.items()) + ' }'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--datapack', type=Path, default=gen_items.DEFAULT_DP)
    parser.add_argument('--game', type=Path, default=gen_items.DEFAULT_GAME, help='unused; check_all passes it')
    parser.add_argument('--out', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        content, counts = generate(args.datapack)
    except (ValueError, OSError, KeyError, IndexError) as error:
        print('gen_merchant_fixtures: ' + str(error), file=sys.stderr)
        return 2
    path = args.out / OUT
    if args.check:
        if not path.exists() or path.read_text() != content:
            print('gen_merchant_fixtures: stale: ' + OUT, file=sys.stderr)
            return 1
    else:
        path.write_text(content)
    print('gen_merchant_fixtures: ' + json.dumps(counts))
    print('gen_merchant_fixtures: ' + ('check passed' if args.check else 'generated'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
