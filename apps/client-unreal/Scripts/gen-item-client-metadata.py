#!/usr/bin/env python3
"""Generate informational arrow classification from the frozen E1 import (no formulas)."""
import argparse
import json
from pathlib import Path
import tomllib

project = Path(__file__).resolve().parents[1]
repo = project.parents[1]
source = repo / 'packages/data/tables-phase4/etc_items.toml'
output = project / 'Source/Nightfall/Items/ItemClientMetadata.h'
args = argparse.ArgumentParser()
args.add_argument('--check', action='store_true')
options = args.parse_args()
table = tomllib.loads(source.read_text())
lines = ['// Generated by Scripts/gen-item-client-metadata.py from E1. Informational metadata only.',
         '#pragma once', '#include "SNightfallV1/ItemsMessage.h"',
         'namespace NightfallItems', '{',
         ' inline bool IsArrow(const FGrpcNightfallV1ItemDefinition& D)', ' {',
         '  if (D.Kind!=EGrpcNightfallV1ItemKind::ITEM_KIND_ETC || !D.Stackable) return false;',
         '  switch(D.TemplateId.Value)', '  {']
for item in sorted(table['items'], key=lambda i: i['template_id']):
    if item['etcitem_type'] != 'ARROW':
        continue
    src = item['source']
    lines.append(f'  // DP@{src["revision"][:8]} {src["file"]}:{src["lines"]}')
    lines.append(f'  case {item["template_id"]}: return D.Name==TEXT({json.dumps(item["name"])});')
lines += ['  default: return false;', '  }', ' }', '}', '']
text = '\n'.join(lines)
if options.check:
    if not output.exists() or output.read_text() != text:
        raise SystemExit('item client metadata drift')
else:
    output.write_text(text)
